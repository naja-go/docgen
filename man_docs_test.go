func TestGenManOutput(t *testing.T) {
	date := time.Date(2026, 11, 25, 0, 0, 0, 0, time.UTC)
	root := &naja.Command{
		Use:   "app",
		Short: "An app",
		Long:  "App does *things*.\nStill the first paragraph.\n\n\nSecond paragraph: a-dash and back\\slash.\n.dot line\n  indented line\n'quote line\n",
	}
	sub := &naja.Command{
		Use:     "serve [flags] <dir>",
		Short:   "Serve it",
		Run:     emptyRun,
		Example: "app serve --port 80 .\n\n  app serve -v .\n.hidden",
	}
	root.AddCommand(sub)
	root.PersistentFlags().NewP("config", "c", "", "config file path")
	sub.Flags().NewP("port", "p", 8080, "port to listen on\n\nsecond usage paragraph")
	sub.Flags().New("verbose", false, "")

	tests := []struct {
		name   string
		cmd    *naja.Command
		header *GenManHeader
		want   string
	}{
		{
			name:   "subcommand",
			cmd:    sub,
			header: &GenManHeader{Date: &date},
			want: `.nh
.TH "APP\-SERVE" "1" "Nov 2026" "Auto generated by naja\-go/naja" ""
.SH NAME
app\-serve \- Serve it
.SH SYNOPSIS
\fBapp serve [flags] <dir>\fP
.SH DESCRIPTION
Serve it
.SH OPTIONS
.TP
\fB\-h\fP, \fB\-\-help\fP[=false]
help for serve
.TP
\fB\-p\fP, \fB\-\-port\fP=8080
port to listen on
.IP
second usage paragraph
.TP
\fB\-\-verbose\fP[=false]
.SH OPTIONS INHERITED FROM PARENT COMMANDS
.TP
\fB\-c\fP, \fB\-\-config\fP=""
config file path
.SH EXAMPLE
.EX
app serve \-\-port 80 .

  app serve \-v .
\&.hidden
.EE
.SH SEE ALSO
\fBapp(1)\fP
.SH HISTORY
25\-Nov\-2026 Auto generated by naja\-go/naja
`,
		},
		{
			name:   "root",
			cmd:    root,
			header: &GenManHeader{Date: &date, Manual: `The "App" Manual`},
			want: `.nh
.TH "APP" "1" "Nov 2026" "Auto generated by naja\-go/naja" "The \(dqApp\(dq Manual"
.SH NAME
app \- An app
.SH SYNOPSIS
\fBapp [flags]\fP
.SH DESCRIPTION
App does *things*.
Still the first paragraph.
.PP
Second paragraph: a\-dash and back\eslash.
\&.dot line
  indented line
\&'quote line
.SH OPTIONS
.TP
\fB\-c\fP, \fB\-\-config\fP=""
config file path
.TP
\fB\-h\fP, \fB\-\-help\fP[=false]
help for app
.SH SEE ALSO
\fBapp\-serve(1)\fP
.SH HISTORY
25\-Nov\-2026 Auto generated by naja\-go/naja
`,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			buf := new(bytes.Buffer)
			if err := GenMan(tt.cmd, tt.header, buf); err != nil {
				t.Fatal(err)
			}
			if got := buf.String(); got != tt.want {
				t.Errorf("unexpected man page\n got:\n%s\nwant:\n%s", got, tt.want)
			}
		})
	}
}
